const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('offlineApi', {
  getStatus: () => ipcRenderer.invoke('get-status'),
  ensureLlamaServer: () => ipcRenderer.invoke('ensure-llama-server'),
  stopLlamaServer: () => ipcRenderer.invoke('stop-llama-server'),
  pickAudio: () => ipcRenderer.invoke('pick-audio'),
  transcribe: (payload) => ipcRenderer.invoke('transcribe', payload),
  transcribeMic: (payload) => ipcRenderer.invoke('transcribe-mic', payload),
  transcribeLiveChunk: (payload) => ipcRenderer.invoke('transcribe-live-chunk', payload),
  saveLiveHistory: (payload) => ipcRenderer.invoke('save-live-history', payload),
  getHistory: () => ipcRenderer.invoke('get-history'),
  clearHistory: () => ipcRenderer.invoke('clear-history'),
  deleteHistoryItem: (id) => ipcRenderer.invoke('delete-history-item', id),
  copyText: (text) => ipcRenderer.invoke('copy-text', text),
  setAutoCopy: (v) => ipcRenderer.invoke('set-auto-copy', v),
  setAutoPaste: (v) => ipcRenderer.invoke('set-auto-paste', v),
  setDefaultLanguage: (v) => ipcRenderer.invoke('set-default-language', v),
  setAutoStopSeconds: (v) => ipcRenderer.invoke('set-auto-stop-seconds', v),
  setAutoStart: (v) => ipcRenderer.invoke('set-auto-start', v),
  onStatusChanged: (cb) => { const h = () => cb(); ipcRenderer.on('status-changed', h); return () => ipcRenderer.removeListener('status-changed', h); },
  setGlobalHotkey: (payload) => ipcRenderer.invoke('set-global-hotkey', payload),
  setLlamaUrl: (url) => ipcRenderer.invoke('set-llama-url', url),
  getModels: () => ipcRenderer.invoke('get-models'),
  setModel: (modelId) => ipcRenderer.invoke('set-model', modelId),
  windowMinimize: () => ipcRenderer.invoke('window-minimize'),
  windowClose: () => ipcRenderer.invoke('window-close'),
  setListeningState: (payload) => ipcRenderer.invoke('listening-state', payload),
  sendListeningLevel: (payload) => ipcRenderer.invoke('listening-level', payload),
  onTranscribeLog: (cb) => { const h = (_e, line) => cb(line); ipcRenderer.on('transcribe-log', h); return () => ipcRenderer.removeListener('transcribe-log', h); },
  onGlobalHotkeyToggle: (cb) => { const h = () => cb(); ipcRenderer.on('global-hotkey-toggle', h); return () => ipcRenderer.removeListener('global-hotkey-toggle', h); },
});
